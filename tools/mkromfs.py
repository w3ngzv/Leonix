"""Pack files into the C source of a read-only filesystem in flash.

Usage: mkromfs.py output.c name=file ...

Each file becomes a PROGMEM array, named in the table that fs/romfs.c
mounts.  The entries are written in the order given.

把文件打包成 flash 中只读文件系统的 C 源文件.

每个文件成为一个 PROGMEM 数组, 登记在 fs/romfs.c 挂载的表中. 各项按给出的顺序
写入.
"""

import re
import sys


def main(argv):
    if len(argv) < 2:
        sys.stderr.write(__doc__ or "")
        return 2
    out = ["// Generated by tools/mkromfs.py; do not edit.",
           "#include <leonix/pgmspace.h>",
           "#include <leonix/romfs.h>",
           ""]
    entries = []
    for i, spec in enumerate(argv[2:]):
        name, _, path = spec.partition("=")
        if not re.fullmatch(r"[A-Za-z0-9_.-]{1,12}", name):
            sys.stderr.write(f"mkromfs: bad name {name!r}\n")
            return 1
        with open(path, "rb") as src:
            data = src.read()
        body = ", ".join(str(b) for b in data)
        out.append(f'static const char name{i}[] PROGMEM = "{name}";')
        out.append(f"static const uint8_t data{i}[] PROGMEM = {{ {body} }};")
        entries.append(f"\t{{ name{i}, data{i}, {len(data)} }},")
    out.append("")
    out.append("const struct romfs_entry romfs_entries[] PROGMEM = {")
    out += entries
    out.append("};")
    out.append(f"const uint8_t romfs_count = {len(entries)};")
    with open(argv[1], "w", encoding="utf-8") as dst:
        dst.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
